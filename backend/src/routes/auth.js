import crypto from 'node:crypto';
import { Router } from 'express';
import bcrypt from 'bcryptjs';
import rateLimit from 'express-rate-limit';
import { z } from 'zod';
import { query, tx } from '../db.js';
import { ah, badRequest, conflict, unauthorized, notFound } from '../lib/errors.js';
import { requireAuth, signToken, sha256 } from '../middleware/auth.js';
import { sendMail } from '../services/mailer.js';
import { config } from '../config.js';

const r = Router();

// brute-force protection on credential endpoints
const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, limit: 20, standardHeaders: true, legacyHeaders: false,
  message: { error: { code: 'RATE_LIMITED', message: 'Too many attempts. Try again in 15 minutes.' } },
});

const PUBLIC_COLS = `farmer_id, name, email, phone, age, gender, village, district, state, farm_location,
                     preferred_lang, email_verified, created_at, updated_at`;

const phone = z.string().trim().transform((s) => s.replace(/\D/g, '').replace(/^91(?=\d{10}$)/, ''))
  .pipe(z.string().regex(/^[6-9]\d{9}$/, 'Enter a valid 10-digit Indian mobile number'));
const password = z.string().min(8, 'Password must be at least 8 characters').max(72)
  .regex(/[A-Za-z]/, 'Password must contain a letter').regex(/\d/, 'Password must contain a number');
const name = z.string().trim().min(2).max(120);
const place = z.string().trim().min(2).max(80);

const registerSchema = z.object({
  name, email: z.string().trim().toLowerCase().email(), phone, password,
  confirmPassword: z.string(),
  village: place, district: place, state: place,
  age: z.coerce.number().int().min(16).max(110).optional(),
  gender: z.enum(['Male', 'Female', 'Other']).optional(),
  preferredLang: z.enum(['en', 'hi']).optional(),
  acceptTerms: z.literal(true, { message: 'You must accept the terms & conditions' }),
}).refine((d) => d.password === d.confirmPassword, { path: ['confirmPassword'], message: 'Passwords do not match' });

async function issueEmailToken(farmerId, purpose, hours) {
  const token = crypto.randomBytes(32).toString('hex');
  await query(
    `INSERT INTO auth_tokens (token_hash, farmer_id, purpose, expires_at) VALUES ($1,$2,$3, now() + make_interval(hours => $4))`,
    [sha256(token), farmerId, purpose, hours]);
  return token;
}

// POST /api/auth/register ---------------------------------------------------------------
r.post('/register', authLimiter, ah(async (req, res) => {
  const d = registerSchema.parse(req.body);
  const hash = await bcrypt.hash(d.password, 10);

  const farmer = await tx(async (c) => {
    const { rows: dup } = await c.query(
      `SELECT lower(email) = $1 AS email_taken, phone = $2 AS phone_taken FROM farmers WHERE lower(email) = $1 OR phone = $2`,
      [d.email, d.phone]);
    if (dup.some((x) => x.email_taken)) throw conflict('An account with this email already exists');
    if (dup.some((x) => x.phone_taken)) throw conflict('An account with this phone number already exists');
    // farmer_id is generated by the DB sequence (FRM-0052 …); thresholds row created by trigger
    const { rows: [f] } = await c.query(
      `INSERT INTO farmers (name, email, phone, password_hash, village, district, state, age, gender, preferred_lang)
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,COALESCE($10,'en')) RETURNING ${PUBLIC_COLS}`,
      [d.name, d.email, d.phone, hash, d.village, d.district, d.state, d.age ?? null, d.gender ?? null, d.preferredLang ?? null]);
    return f;
  });

  // optional verification e-mail (logged to console when SMTP is not configured)
  const vt = await issueEmailToken(farmer.farmer_id, 'VERIFY', 48);
  sendMail(farmer.email, 'Verify your SoilSense account',
    `Namaste ${farmer.name},\n\nYour Farmer ID is ${farmer.farmer_id}.\nVerify your e-mail: ${config.appUrl}/verify-email?token=${vt}\n`).catch(() => {});

  const { token, expiresAt } = signToken(farmer.farmer_id, true);
  res.status(201).json({
    message: `Registration successful. Your Farmer ID is ${farmer.farmer_id}.`,
    farmer, token, expiresAt,
    ...(config.isProd ? {} : { devVerificationToken: vt }),
  });
}));

// POST /api/auth/login ------------------------------------------------------------------
const loginSchema = z.object({
  identifier: z.string().trim().min(3).optional(),           // email, phone or Farmer ID
  email: z.string().trim().optional(),                       // accepted for convenience
  password: z.string().min(1),
  remember: z.boolean().optional(),
}).refine((d) => d.identifier || d.email, { message: 'Email, phone or Farmer ID is required', path: ['identifier'] });

r.post('/login', authLimiter, ah(async (req, res) => {
  const d = loginSchema.parse(req.body);
  const id = (d.identifier || d.email).toLowerCase();
  const digits = id.replace(/\D/g, '').replace(/^91(?=\d{10}$)/, '');
  const { rows: [f] } = await query(
    `SELECT ${PUBLIC_COLS}, password_hash FROM farmers
      WHERE lower(email) = $1 OR lower(farmer_id) = $1 OR ($2 <> '' AND phone = $2) LIMIT 1`, [id, digits]);
  // same error and similar timing whether the user exists or not
  const ok = await bcrypt.compare(d.password, f?.password_hash ?? '$2a$10$invalidinvalidinvalidinvalidinvalidinvalidinvalidinv');
  if (!f || !ok) throw unauthorized('Incorrect login details');
  delete f.password_hash;
  const { token, expiresAt } = signToken(f.farmer_id, d.remember);
  res.json({ farmer: f, token, expiresAt });
}));

// POST /api/auth/logout  (revokes the current JWT) --------------------------------------
r.post('/logout', requireAuth, ah(async (req, res) => {
  await query(
    `INSERT INTO auth_tokens (token_hash, farmer_id, purpose, expires_at)
     VALUES ($1,$2,'REVOKED', to_timestamp($3)) ON CONFLICT DO NOTHING`,
    [sha256(req.user.jti), req.user.farmerId, req.user.exp]);
  res.json({ message: 'Logged out' });
}));

// GET /api/auth/profile -----------------------------------------------------------------
r.get('/profile', requireAuth, ah(async (req, res) => {
  const { rows: [f] } = await query(
    `SELECT ${PUBLIC_COLS},
            (SELECT count(*)::int FROM fields WHERE farmer_id = $1) AS field_count,
            (SELECT COALESCE(sum(area_acres),0) FROM fields WHERE farmer_id = $1) AS total_area_acres
       FROM farmers WHERE farmer_id = $1`, [req.user.farmerId]);
  if (!f) throw notFound('Farmer');
  res.json({ farmer: f });
}));

// PUT /api/auth/profile -----------------------------------------------------------------
export const profileUpdateSchema = z.object({
  name: name.optional(), phone: phone.optional(),
  email: z.string().trim().toLowerCase().email().optional(),
  village: place.optional(), district: place.optional(), state: place.optional(),
  age: z.coerce.number().int().min(16).max(110).nullable().optional(),
  gender: z.enum(['Male', 'Female', 'Other']).nullable().optional(),
  preferredLang: z.enum(['en', 'hi']).optional(),
}).strict();

export async function updateFarmer(farmerId, body) {
  const d = profileUpdateSchema.parse(body);
  const map = { name: 'name', phone: 'phone', email: 'email', village: 'village', district: 'district',
    state: 'state', age: 'age', gender: 'gender', preferredLang: 'preferred_lang' };
  const sets = []; const vals = [];
  for (const [k, col] of Object.entries(map)) {
    if (d[k] !== undefined) { vals.push(d[k]); sets.push(`${col} = $${vals.length}`); }
  }
  if (d.email) sets.push('email_verified = false');
  if (!sets.length) throw badRequest('No fields to update');
  vals.push(farmerId);
  const { rows: [f] } = await query(
    `UPDATE farmers SET ${sets.join(', ')} WHERE farmer_id = $${vals.length} RETURNING ${PUBLIC_COLS}`, vals);
  return f;
}

r.put('/profile', requireAuth, ah(async (req, res) => {
  res.json({ farmer: await updateFarmer(req.user.farmerId, req.body) });
}));

// PUT /api/auth/password ---------------------------------------------------------------
r.put('/password', requireAuth, ah(async (req, res) => {
  const d = z.object({ currentPassword: z.string(), newPassword: password }).parse(req.body);
  const { rows: [f] } = await query('SELECT password_hash FROM farmers WHERE farmer_id = $1', [req.user.farmerId]);
  if (!(await bcrypt.compare(d.currentPassword, f.password_hash))) throw unauthorized('Current password is incorrect');
  await query('UPDATE farmers SET password_hash = $1 WHERE farmer_id = $2', [await bcrypt.hash(d.newPassword, 10), req.user.farmerId]);
  res.json({ message: 'Password updated' });
}));

// POST /api/auth/verify-email  { token }  — or { resend: true } with auth -----------------
r.post('/verify-email', ah(async (req, res, next) => {
  if (req.body?.resend) {
    return requireAuth(req, res, async (err) => {
      if (err) return next(err);
      try {
        const { rows: [f] } = await query('SELECT email, name, email_verified FROM farmers WHERE farmer_id = $1', [req.user.farmerId]);
        if (f.email_verified) return res.json({ message: 'E-mail already verified' });
        const vt = await issueEmailToken(req.user.farmerId, 'VERIFY', 48);
        await sendMail(f.email, 'Verify your SoilSense account', `Verify your e-mail: ${config.appUrl}/verify-email?token=${vt}`);
        res.json({ message: 'Verification e-mail sent', ...(config.isProd ? {} : { devVerificationToken: vt }) });
      } catch (e) { next(e); }
    });
  }
  const { token } = z.object({ token: z.string().length(64) }).parse(req.body);
  const updated = await tx(async (c) => {
    const { rows: [t] } = await c.query(
      `UPDATE auth_tokens SET used_at = now()
        WHERE token_hash = $1 AND purpose = 'VERIFY' AND used_at IS NULL AND expires_at > now()
        RETURNING farmer_id`, [sha256(token)]);
    if (!t) return null;
    await c.query('UPDATE farmers SET email_verified = true WHERE farmer_id = $1', [t.farmer_id]);
    return t.farmer_id;
  });
  if (!updated) throw badRequest('Verification link is invalid or has expired');
  res.json({ message: 'E-mail verified', farmer_id: updated });
}));

// POST /api/auth/forgot-password  { email } ---------------------------------------------
r.post('/forgot-password', authLimiter, ah(async (req, res) => {
  const { email } = z.object({ email: z.string().trim().toLowerCase().email() }).parse(req.body);
  const { rows: [f] } = await query('SELECT farmer_id, name FROM farmers WHERE lower(email) = $1', [email]);
  let devToken;
  if (f) {
    devToken = await issueEmailToken(f.farmer_id, 'RESET', 1);
    await sendMail(email, 'Reset your SoilSense password',
      `Namaste ${f.name},\n\nReset your password (valid for 1 hour): ${config.appUrl}/reset-password?token=${devToken}\n`);
  }
  // identical response whether or not the account exists
  res.json({ message: 'If that e-mail is registered, a reset link has been sent.', ...(config.isProd || !devToken ? {} : { devResetToken: devToken }) });
}));

// POST /api/auth/reset-password  { token, password } ------------------------------------
r.post('/reset-password', authLimiter, ah(async (req, res) => {
  const d = z.object({ token: z.string().length(64), password }).parse(req.body);
  const ok = await tx(async (c) => {
    const { rows: [t] } = await c.query(
      `UPDATE auth_tokens SET used_at = now()
        WHERE token_hash = $1 AND purpose = 'RESET' AND used_at IS NULL AND expires_at > now()
        RETURNING farmer_id`, [sha256(d.token)]);
    if (!t) return false;
    await c.query('UPDATE farmers SET password_hash = $1 WHERE farmer_id = $2', [await bcrypt.hash(d.password, 10), t.farmer_id]);
    return true;
  });
  if (!ok) throw badRequest('Reset link is invalid or has expired');
  res.json({ message: 'Password has been reset. You can log in now.' });
}));

export default r;
